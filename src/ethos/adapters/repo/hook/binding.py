"""Read the exact repository-family Git hook runtime binding."""

from __future__ import annotations

import hashlib
import os
import shlex
import sys
from pathlib import Path
from typing import TYPE_CHECKING
from typing import NotRequired
from typing import TypedDict

from ethos.adapters.repo.git import git_common_dir
from ethos.adapters.repo.git import run_git
from ethos.adapters.repo.runtime.authority import expected_runtime_build
from ethos.adapters.repo.runtime.selection import SelectedRuntime
from ethos.adapters.repo.runtime.selection import current_runtime
from ethos.adapters.repo.runtime.selection import runtime_command

if TYPE_CHECKING:
    from ethos.repository.release.identity import BuildIdentity

HOOK_NAMES = ("pre-commit", "pre-push", "reference-transaction")


class HookRuntimeBinding(TypedDict):
    """One repository family's exact generated-hook runtime provenance."""

    hooks_path: str
    runtime_manifest_path: str
    runtime_digest: str
    wheel_sha256: str
    product_version: str
    distribution_version: str
    channel: str
    acceptance_state: str
    source_commit: str
    source_tree: str
    expected_source_commit: str
    expected_source_tree: str
    current: bool
    next_action: str
    python: str
    scripts: list[str]
    required_gaps: list[str]
    generation_cleanup: NotRequired[dict[str, list[str]]]
    legacy_runtime_locator: NotRequired[dict[str, object]]
    linked_worktrees: NotRequired[list[dict[str, str]]]


def hook_launcher(name: str) -> str:
    """Render a Git-shell projection over the canonical runtime selector."""
    if name not in HOOK_NAMES:
        message = f"hook_name_invalid:{name}"
        raise ValueError(message)
    executable = "Scripts/python.exe" if os.name == "nt" else "bin/python"
    return (
        "#!/bin/sh\n"
        "# Generated by ethos hook install; Python owns all hook semantics.\n"
        'HOOK_DIR=${0%/*}; [ "$HOOK_DIR" = "$0" ] && HOOK_DIR=.\n'
        'HOOK_DIR=$(CDPATH= cd "$HOOK_DIR" && pwd)\n'
        'RUNTIME_ROOT="$HOOK_DIR/../../runtime"\n'
        'CURRENT="$RUNTIME_ROOT/CURRENT"\n'
        'if [ -L "$CURRENT" ] || [ ! -f "$CURRENT" ]; then\n'
        '  printf "%s\\n" \'{"required_gaps":["hook_runtime_current_missing"],'
        '"state":"blocked","verdict":"block"}\' >&2\n'
        "  exit 1\n"
        "fi\n"
        'RUNTIME_DIGEST=$(cat "$CURRENT") || exit 1\n'
        'case "$RUNTIME_DIGEST" in *[!0-9a-f]*|"") exit 1;; esac\n'
        '[ "${#RUNTIME_DIGEST}" -eq 64 ] || exit 1\n'
        'RUNTIME="$RUNTIME_ROOT/$RUNTIME_DIGEST"\n'
        'if [ -L "$RUNTIME" ] || [ ! -d "$RUNTIME" ]; then exit 1; fi\n'
        f'exec "$RUNTIME_ROOT/$RUNTIME_DIGEST/python/{executable}" '
        f'-I -m ethos.cli hook run {name} "$@"\n'
    )


def hook_generation_digest(launchers: dict[str, str]) -> str:
    """Return the canonical identity of one complete declared launcher set."""
    if tuple(launchers) != HOOK_NAMES:
        message = "hook_launcher_projection_invalid"
        raise ValueError(message)
    return hashlib.sha256(
        b"".join(
            name.encode() + b"\0" + content.encode() + b"\0" for name, content in launchers.items()
        )
    ).hexdigest()


def hook_runtime_binding(
    root: Path,
    *,
    expected_build: BuildIdentity | None = None,
) -> HookRuntimeBinding:
    """Observe the configured common-dir hooks and selected runtime."""
    repo = root.resolve()
    common = Path(git_common_dir(repo))
    generations = common / "ethos" / "hooks"
    configured = _configured_hooks_path(repo)
    hooks = configured or generations
    valid_generation = (
        configured is not None
        and configured.parent == generations
        and not generations.parent.is_symlink()
        and not generations.is_symlink()
        and not configured.is_symlink()
        and _valid_digest(configured.name)
    )
    expected_build_identity, _source_root = _expected_build(repo, expected_build)
    selected, selection_gap = _selected_runtime(common)
    gaps: list[str] = []
    if not valid_generation:
        gaps.append("write_admission_not_armed:core.hooksPath")
    if selection_gap:
        gaps.append(f"write_admission_not_armed:{selection_gap}")
    if expected_build_identity is None:
        gaps.append("write_admission_not_armed:runtime_expected_build_unavailable")
    elif selected is not None and selected.build != expected_build_identity:
        gaps.append("write_admission_not_armed:runtime_build_stale")
    gaps.extend(gap for name in HOOK_NAMES if (gap := _launcher_gap(hooks / name, name)))
    if valid_generation:
        expected_launchers = {name: hook_launcher(name) for name in HOOK_NAMES}
        if hooks.name != hook_generation_digest(expected_launchers):
            gaps.append("write_admission_not_armed:hook_generation_digest")
    return {
        "hooks_path": hooks.as_posix(),
        "runtime_manifest_path": selected.manifest.as_posix() if selected else "",
        "runtime_digest": selected.digest if selected else "",
        "wheel_sha256": selected.wheel_sha256 if selected else "",
        "product_version": selected.build.product_version if selected else "",
        "distribution_version": selected.build.distribution_version if selected else "",
        "channel": selected.build.channel if selected else "",
        "acceptance_state": selected.build.acceptance_state if selected else "",
        "source_commit": selected.build.source_commit if selected else "",
        "source_tree": selected.build.source_tree if selected else "",
        "expected_source_commit": (
            expected_build_identity.source_commit if expected_build_identity else ""
        ),
        "expected_source_tree": (
            expected_build_identity.source_tree if expected_build_identity else ""
        ),
        "current": not gaps,
        "next_action": _repair_action(repo, selected) if gaps else "",
        "python": selected.python.as_posix() if selected else "",
        "scripts": list(HOOK_NAMES),
        "required_gaps": gaps,
    }


def _launcher_gap(launcher: Path, name: str) -> str:
    if launcher.is_symlink() or not launcher.is_file() or not os.access(launcher, os.X_OK):
        return f"write_admission_not_armed:{name}_launcher_missing"
    try:
        current = launcher.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        current = ""
    return (
        "" if current == hook_launcher(name) else f"write_admission_not_armed:{name}_launcher_drift"
    )


def _selected_runtime(common: Path) -> tuple[SelectedRuntime | None, str]:
    try:
        return current_runtime(common), ""
    except ValueError as error:
        reason = str(error)
        if reason in {"hook_runtime_current_missing", "hook_runtime_current_invalid"}:
            return None, "runtime_current"
        return None, "runtime_manifest"


def _repair_action(repo: Path, selected: SelectedRuntime | None) -> str:
    if selected is not None:
        return runtime_command(repo, "hook", "install", "--root", repo.as_posix(), "--json")
    return shlex.join(
        (
            Path(sys.executable).resolve().as_posix(),
            "-I",
            "-m",
            "ethos.cli",
            "hook",
            "install",
            "--root",
            repo.as_posix(),
            "--json",
        )
    )


def _expected_build(
    repo: Path,
    selected: BuildIdentity | None,
) -> tuple[BuildIdentity | None, Path | None]:
    if selected is not None:
        return selected, None
    try:
        return expected_runtime_build(repo)
    except (OSError, RuntimeError, ValueError):
        return None, None


def _valid_digest(value: str) -> bool:
    return len(value) == 64 and not set(value) - set("0123456789abcdef")


def _configured_hooks_path(root: Path) -> Path | None:
    completed = run_git(root, "config", "--path", "--get", "core.hooksPath", check=False)
    if completed.returncode or not completed.stdout.strip():
        return None
    configured = Path(completed.stdout.strip())
    return configured.absolute() if configured.is_absolute() else (root / configured).absolute()
