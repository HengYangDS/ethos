def test_artifact_partition_cannot_replace_integrity_evidence() -> None:
    """A selected static path is not evidence that its locked or generated bytes match."""
    tree = "a" * 40
    provider = "ethos.adapters.gates.code_quality:static_report"
    owner = ".config/checks/ci-projection/policy.toml"
    policy = {
        "owner": {
            "quality_floor_version": 2,
            "code_correctness_map": {"static-analysis": "static"},
            "quality_subjects": {"static-analysis": ["authored.py", "generated.py"]},
            "source_contracts": [
                {
                    "kind": "generated",
                    "input_refs": [owner],
                    "members": {"generated.py": [owner, "generated.py"]},
                    "integrity_gate": "integrity",
                }
            ],
        },
        "gates": [
            {
                "id": "static",
                "execution_identity": ["provider", provider],
                "execution_mode": "provider",
                "tool_adapter": "ethos",
            }
        ],
    }
    report = {
        "verdict": "pass",
        "quality_evidence": {
            "axis": "static-analysis",
            "source_tree": tree,
            "selected_paths": ["authored.py", "generated.py"],
            "authored_paths": ["authored.py"],
            "artifact_paths": ["generated.py"],
        },
    }
    check = {
        "action_id": "static",
        "stdout": json.dumps(
            {
                "gate": "static",
                "providers": [{"provider": provider, "report": report}],
            }
        ),
    }
    assert quality_obligation_gaps(policy, [check], source_tree=tree) == (
        "source_integrity_unproven:generated.py",
    )


@pytest.mark.parametrize("defect", ["none", "bytes", "missing", "incomplete"])
def test_generated_observer_rebuilds_complete_native_owner(tmp_path: Path, defect: str) -> None:
    """The product compares native outputs, not a producer's verdict or directory label."""
    repo = init_git_repo(tmp_path / "repository")
    with (repo / ".gitattributes").open("a", encoding="utf-8") as attributes:
        attributes.write("template.txt -text\ngenerated.py -text\nother.py -text\n")
    content = b"import math\nVALUE = 42\r\n"
    (repo / "template.txt").write_bytes(content)
    (repo / "generated.py").write_bytes(content if defect != "bytes" else content + b"# drift\n")
    declaration = ".config/checks/ci-projection/policy.toml"
    owner = repo / declaration
    owner.parent.mkdir(parents=True)
    entries = [{"template": "template.txt", "projection": "generated.py"}]
    if defect == "incomplete":
        entries.append({"template": "template.txt", "projection": "other.py"})
        (repo / "other.py").write_bytes(content)
    owner.write_text(
        tomli_w.dumps({"schema": "ethos-ci-template-consistency-v1", "projection": entries})
    )
    write_test_profile(
        repo,
        profile_id="example",
        proof={
            "gate_registry": "system/gates.toml",
            "source_contracts": [
                {
                    "kind": "generated",
                    "input_refs": [declaration],
                    "members": {"generated.py": [declaration, "generated.py"]},
                    "integrity_gate": "integrity",
                }
            ],
        },
    )
    commit_fixture(repo, "declare complete native copy relation")
    if defect == "missing":
        (repo / "generated.py").unlink()
    observer = importlib.import_module("ethos.adapters.gates.provenance.observation")
    report = observer.integrity_report(repo)
    if defect == "none":
        assert report["verdict"] == "pass", report
        integrity = report["source_integrity"]
        assert isinstance(integrity, dict)
        assert integrity["members"] == {
            "generated.py": {
                "kind": "generated",
                "input_ref": declaration,
                "member": "generated.py",
            }
        }
    else:
        assert report["verdict"] != "pass", report
        assert report["required_gaps"]


@pytest.mark.parametrize(
    "defect", ["none", "stale-tree", "wrong-provider", "forged-stdout", "duplicate", "members"]
)
def test_source_integrity_join_requires_exact_product_observation(defect: str) -> None:
    """Current byte evidence must retain its native provider, exact scope, and execution."""
    tree = "a" * 40
    provider = "ethos.adapters.gates.provenance.observation:integrity_report"
    declaration = ".config/checks/ci-projection/policy.toml"
    members = {
        "generated.py": {"kind": "generated", "input_ref": declaration, "member": "generated.py"}
    }
    report = {"verdict": "pass", "source_integrity": {"source_tree": tree, "members": members}}
    policy = {
        "owner": {
            "source_contracts": [
                {
                    "kind": "generated",
                    "input_refs": [declaration],
                    "members": {"generated.py": [declaration, "generated.py"]},
                    "integrity_gate": "integrity",
                }
            ]
        },
        "gates": [
            {
                "id": "integrity",
                "execution_mode": "provider",
                "execution_identity": ["provider", provider],
            }
        ],
    }
    observed = copy.deepcopy(report)
    integrity = observed["source_integrity"]
    assert isinstance(integrity, dict)
    item = {"provider": provider, "report": observed}
    payload = {"gate": "integrity", "providers": [item]}
    check = {
        "action_id": "integrity",
        "command": ["provider", provider],
        "exit_code": 0,
        "verdict": "pass",
        "stdout": "",
    }
    if defect == "stale-tree":
        integrity["source_tree"] = "b" * 40
    elif defect == "wrong-provider":
        item["provider"] = "untrusted:report"
    elif defect == "forged-stdout":
        check["exit_code"] = 1
        check["verdict"] = "block"
    elif defect == "duplicate":
        payload["providers"].append(copy.deepcopy(item))
    elif defect == "members":
        integrity["members"] = {}
    check["stdout"] = json.dumps(payload)
    gaps = quality_obligation_gaps(policy, [check], source_tree=tree)
    assert gaps == (() if defect == "none" else ("source_integrity_unproven:generated.py",))
